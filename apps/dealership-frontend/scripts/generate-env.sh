#!/usr/bin/env bash
# Generates a .env.local file interactively for local development.

set -euo pipefail

ENV_FILE="${1:-.env.local}"

if [[ -f "$ENV_FILE" ]]; then
  read -rp "${ENV_FILE} already exists. Overwrite? (y/N) " overwrite
  case "${overwrite:-}" in
    y|Y)
      echo "Overwriting ${ENV_FILE}..."
      ;;
    *)
      echo "Aborting. No changes made."
      exit 0
      ;;
  esac
fi

read -rp "Supabase URL (e.g. https://your-project.supabase.co): " supabase_url
read -rp "Supabase anon key: " supabase_anon_key
read -rp "Google Gemini API key: " gemini_api_key

cat > "$ENV_FILE" <<EOF
# Generated by scripts/generate-env.sh on $(date +%Y-%m-%d)
VITE_SUPABASE_URL=${supabase_url}
VITE_SUPABASE_ANON_KEY=${supabase_anon_key}
VITE_GEMINI_API_KEY=${gemini_api_key}
NODE_ENV=development
EOF

echo "Created ${ENV_FILE}."
echo "Remember to keep this file out of version control."
