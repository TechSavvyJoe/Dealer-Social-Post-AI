#!/bin/bash

echo "========================================="
echo "PocketBase Configuration Fix Script"
echo "========================================="
echo ""

POCKETBASE_URL="https://even-terry-exactly-unique.trycloudflare.com"

echo "This script will help you reset PocketBase API rules to working defaults."
echo ""
echo "⚠️  IMPORTANT: You need to do this manually in PocketBase Admin UI"
echo "   because API rules can only be changed through the admin interface."
echo ""
echo "Step-by-step instructions:"
echo ""
echo "1. Open PocketBase Admin: ${POCKETBASE_URL}/_/"
echo ""
echo "2. Go to: Collections → users → API Rules tab"
echo ""
echo "3. SET ALL RULES TO EMPTY (leave them blank):"
echo "   - ListRule: (leave EMPTY)"
echo "   - ViewRule: (leave EMPTY)"  
echo "   - CreateRule: (leave EMPTY)"
echo "   - UpdateRule: (leave EMPTY)"
echo "   - DeleteRule: (leave EMPTY)"
echo ""
echo "   ℹ️  Empty rules mean NO RESTRICTIONS"
echo "   ℹ️  This allows the app to work while we debug"
echo ""
echo "4. Click SAVE"
echo ""
echo "5. Go to: Collections → users → Options tab"
echo ""
echo "6. Scroll to 'API Rules' section and verify:"
echo "   ✓ Auth is ENABLED"
echo "   ✓ 'Use custom auth rules' is UNCHECKED (or empty)"
echo ""
echo "7. Click SAVE"
echo ""
echo "========================================="
echo "After completing these steps:"
echo "========================================="
echo ""
echo "Test authentication:"
echo "  1. Refresh your browser"
echo "  2. Try to log in"
echo "  3. Should work now!"
echo ""
echo "Test user management:"
echo "  1. Go to Team Management tab"
echo "  2. Jose should appear in the user list"
echo "  3. You should be able to create/edit/delete users"
echo ""
echo "========================================="
echo ""
read -p "Press ENTER when you've completed the steps above..."

echo ""
echo "Testing PocketBase connection..."
HEALTH=$(curl -s "${POCKETBASE_URL}/api/health" 2>&1)
if echo "$HEALTH" | grep -q "healthy"; then
    echo "✅ PocketBase is running"
else
    echo "❌ PocketBase connection failed"
fi

echo ""
echo "Testing users collection (public access)..."
USERS=$(curl -s "${POCKETBASE_URL}/api/collections/users/records" 2>&1)
if echo "$USERS" | grep -q "items"; then
    echo "✅ Users collection is accessible"
    USER_COUNT=$(echo "$USERS" | grep -o '"totalItems":[0-9]*' | grep -o '[0-9]*')
    echo "📊 Found $USER_COUNT users in database"
else
    echo "⚠️  Users collection requires authentication (this is normal)"
fi

echo ""
echo "========================================="
echo "Next Steps:"
echo "========================================="
echo ""
echo "1. Try logging into your app: http://localhost:3000"
echo "2. Check browser console for any errors"
echo "3. If login works, check Team Management tab for Jose"
echo ""
echo "If you still have issues, check browser console and share the error message."
echo ""
